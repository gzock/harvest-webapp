#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateTypes, generatorVersions } from '@harvest/api-codegen';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = resolve(root, 'contracts/openapi.json');
const metadataPath = resolve(root, 'contracts/openapi.source.json');
const outputPath = resolve(root, 'src/app/api/schema.ts');
const sha256 = text => createHash('sha256').update(text).digest('hex');
const action = process.argv[2] || 'check';
if (!['sync', 'generate', 'check'].includes(action)) throw new Error('Use sync, generate, or check');

if (action === 'sync') {
  const sourcePath = resolve(process.argv[3] || resolve(root, '../harvest-serverless-api/contracts/openapi.json'));
  const schema = await readFile(sourcePath, 'utf8');
  JSON.parse(schema);
  const sourceRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: dirname(sourcePath), encoding: 'utf8' }).trim();
  const git = args => execFileSync('git', args, { cwd: sourceRoot, encoding: 'utf8' }).trim();
  const metadata = {
    sourceRepository: basename(sourceRoot),
    sourcePath: relative(sourceRoot, sourcePath),
    sourceCommit: git(['rev-parse', 'HEAD']),
    sourceWorkingTreeDirty: Boolean(git(['status', '--porcelain'])),
    schemaSha256: sha256(schema),
    ...generatorVersions,
  };
  await writeFile(snapshotPath, schema);
  await writeFile(metadataPath, JSON.stringify(metadata, null, 2) + '\n');
}

const schemaText = await readFile(snapshotPath, 'utf8');
const metadata = JSON.parse(await readFile(metadataPath, 'utf8'));
if (metadata.schemaSha256 !== sha256(schemaText)) throw new Error('Snapshot hash mismatch; run npm run api:sync from the backend contract');
if (metadata.generator !== generatorVersions.generator || metadata.generatorTypeScript !== generatorVersions.generatorTypeScript) {
  throw new Error('Generator version changed; run npm run api:sync to refresh the provenance and generated types');
}
const schema = JSON.parse(schemaText);
const generated = `/**\n * Generated by ${generatorVersions.generator}. Do not edit.\n * Source schema SHA-256: ${metadata.schemaSha256}\n * Regenerate with npm run api:generate.\n */\n\n` + await generateTypes(schema);
if (action === 'check') {
  const actual = await readFile(outputPath, 'utf8');
  if (actual !== generated) throw new Error('Generated API types are stale; run npm run api:generate');
  console.log('API snapshot hash and generated types match');
} else {
  await writeFile(outputPath, generated);
  console.log('Generated src/app/api/schema.ts from the versioned API snapshot');
}
